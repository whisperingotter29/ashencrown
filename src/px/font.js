// In-world pixel fonts (damage numbers, combat callouts, marker labels). Every glyph is a
// hand-made bitmap at the art-pixel density; text is never scaled, a bigger size is its own font.
//   REGULAR  8 px cap height, 2 px descenders, 2 px stems: damage numbers, callouts, labels
//   BIG     12 px cap height, 3 px stems, capitals and digits: crits, shouts, pop-in frames
//   TINY     the old 5-row font, kept for small UI canvases (HUD orbs) that have their own scale
// drawText(L, x, y, text, color, size, outline, a, mask): size 1 = REGULAR, 2+ = BIG (falls back
// to REGULAR when the text has a character BIG lacks), or pass a font object (TINY).

// glyph rows: '#' ink, '.' empty. Rows below the cap height are descenders.
const mk = (name, h, desc, space, glyphs, opts = {}) => {
  const g = {};
  for (const [ch, rows] of Object.entries(glyphs)) {
    const r = typeof rows === 'string' ? rows.split('/') : rows;
    const w = Math.max(...r.map((s) => s.length));
    g[ch] = { w, rows: r };
  }
  g[' '] = { w: space, rows: [] };
  return { name, h, desc, glyphs: g, gap: 1, upper: !!opts.upper, shadow: !!opts.shadow };
};

