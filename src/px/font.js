export const REGULAR = mk('regular', 8, 2, 3, REG);
export const BIG = mk('big', 12, 1, 5, BIG_G, { upper: true, shadow: true });
export const TINY = mk('tiny', 5, 0, 2, TINY_G, { upper: true });
export const FONT_H = REGULAR.h;      // cap height of the regular in-world font
export const FONT_BIG_H = BIG.h;

const BOX = { w: 6, rows: '######/##..##/##..##/##..##/##..##/##..##/##..##/######'.split('/') };
function glyph(F, ch) {
  const g = F.glyphs;
  return g[ch] || (F.upper ? g[ch.toUpperCase()] : g[ch.toLowerCase()] || g[ch.toUpperCase()]) || (F === REGULAR ? BOX : g['?'] || BOX);
}
const has = (F, ch) => !!(F.glyphs[ch] || F.glyphs[ch.toUpperCase()]);

// size -> font. Sizes >= 2 use BIG when it covers every character of the text.
export function fontFor(text, size = 1) {
  if (size && typeof size === 'object') return size;
  if (size >= 2) { for (const ch of String(text)) if (!has(BIG, ch)) return REGULAR; return BIG; }
  return REGULAR;
}
export function textWidth(text, size = 1) {
  const F = fontFor(text, size);
  let w = 0;
  for (const ch of String(text)) w += glyph(F, ch).w + F.gap;
  return Math.max(0, w - F.gap);
}
export function textHeight(text, size = 1) { return fontFor(text, size).h; }

// Draw `text` with the top-left of its cap box at (x, y) into a pixel sink with .px(x, y, rgb, a).
// color: rgb or fn(gx, gy, capH) -> rgb, with gx the pixel column in the text and gy the row in
// the glyph (0 = cap top). outline: rgb for a 1px ring around the glyphs (BIG also gets a 1px
// drop shadow under it). Descenders hang below the cap box.
export function drawText(L, x, y, text, color, size = 1, outline = null, a = 1, mask = null) {
  text = String(text);
  const F = fontFor(text, size);
  x = Math.round(x); y = Math.round(y);
  const sh = outline && F.shadow ? 1 : 0;
  const w = textWidth(text, F) + 2, h = F.h + F.desc + 2 + sh;
  const on = new Uint8Array(w * h);
  let cx = 0;
  for (const ch of text) {
    const g = glyph(F, ch);
    for (let r = 0; r < g.rows.length && r < F.h + F.desc; r++) {
      const row = g.rows[r];
      for (let c = 0; c < row.length; c++) if (row.charCodeAt(c) === 35) on[(r + 1) * w + cx + c + 1] = 1;
    }
    cx += g.w + F.gap;
  }
  const fn = typeof color === 'function';
  const ring = (i, j) => {
    for (let dj = -1; dj <= 1; dj++) for (let di = -1; di <= 1; di++) {
      const ii = i + di, jj = j + dj;
      if (ii >= 0 && jj >= 0 && ii < w && jj < h && on[jj * w + ii] === 1) return true;
    }
    return false;
  };
  if (outline) for (let j = 0; j < h; j++) for (let i = 0; i < w; i++) if (!on[j * w + i] && ring(i, j)) on[j * w + i] = 2;
  if (sh) for (let j = h - 1; j > 0; j--) for (let i = 0; i < w; i++) if (!on[j * w + i] && on[(j - 1) * w + i] === 2) on[j * w + i] = 3;
  for (let j = 0; j < h; j++) for (let i = 0; i < w; i++) {
    const v = on[j * w + i];
    if (!v) continue;
    const X = x + i - 1, Y = y + j - 1;
    if (mask && !mask(X, Y)) continue;
    if (v === 1) L.px(X, Y, fn ? color(i - 1, j - 1, F.h) : color, a);
    else L.px(X, Y, outline, a);
  }
}
